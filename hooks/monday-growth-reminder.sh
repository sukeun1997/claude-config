#!/usr/bin/env bash
# SessionStart 훅: 매주 월요일에만 성장 리마인더를 출력한다.
# WHY: 떠난 동료의 고별사 핵심(주도성/장기적 사고)을 주 1회 의식적으로 되새기기 위함.
#      vault Home 임베드는 Obsidian을 열어야 보이므로, 세션 시작 시점에도 강제 노출한다.
# 출처 노트: ~/vault/40 개인/성장/떠나는 동료의 마지막 조언 - 주도성과 장기적 사고.md

# date +%u : 1=월 ... 7=일. 월요일이 아니면 조용히 종료(다른 요일엔 아무 출력 없음).
[ "$(date +%u)" = "1" ] || exit 0

cat <<'EOF'
🔁 [월요일 성장 리마인더 — 떠나는 동료의 마지막 조언]
한 줄: "지시가 아니라 문제를 받아라. 묻기 전에 가설을 만들어라."

1. 일을 "지시 단위"가 아니라 "문제 단위"로 받는다. 리더에겐 목적·목표라는 뼈대만 받아오고, 빈 공간은 내 삽질로 채운다.
2. 묻기 전에 가설을 만든다. "어떻게 해요?"(떠먹여 달라) ❌ → "A/B 둘 다 파봤는데 B가 X 때문에 막힙니다. 놓친 제약 있나요?" ✅
3. 엉성해도 내 논리가 담긴 기획서를 들고 가 전쟁하듯 논의한다. 완성도보다 주도권.
4. 재밌어 보이고 해볼 만한 영역엔 하이에나처럼 달려든다. "제 업무 아닌데요"는 스스로를 부품으로 만드는 짓.
5. 장기 이득을 본다. 눈앞의 푼돈이 아니라 "행복한 인생". 회사를 이용해 성장한다 — 회사와 나의 이해가 정렬되는 지점.

(전문/해설: ~/vault/40 개인/성장/떠나는 동료의 마지막 조언 - 주도성과 장기적 사고.md)
EOF
